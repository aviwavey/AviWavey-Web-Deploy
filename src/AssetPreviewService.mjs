// Only catalogue-approved public demo files are fetched; this is not an arbitrary URL proxy.
async function assetPreviewService(request) {
 const path=new URL(request.url).pathname;
 if(!path.startsWith('/api/asset-preview/'))return null;
 if(!['GET','HEAD'].includes(request.method))return new Response('Method not allowed',{status:405});
 const match=path.match(/^\/api\/asset-preview\/([^/]+)\/(\d+)\/[^/]+$/);
 const entry=match&&assetPreviewCatalogue[decodeURIComponent(match[1])]?.resources[Number(match[2])];
 if(!entry)return Response.json({message:'Preview file not found.'},{status:404});
 const fail=(message,status=502)=>Response.json({message},{status,headers:{'cache-control':'no-store'}});
 try {
  let target=entry.url,response;
  const origin=new URL(target).hostname;
  for(let i=0;i<5;i++){
   response=await fetch(target,{method:request.method,redirect:'manual',headers:{'User-Agent':'AVIWavey-AssetPreview/1.0'},cf:{cacheTtl:86400,cacheEverything:true},signal:AbortSignal.timeout(45000)});
   if(![301,302,303,307,308].includes(response.status))break;
   const next=new URL(response.headers.get('location'),target);
   if(next.protocol!=='https:'||!(next.hostname===origin||(origin==='archive.org'&&next.hostname.endsWith('.archive.org'))))return fail('The source moved to an unverified host.');
   target=next.href;
  }
  if(!response?.ok)return fail('The original source is temporarily unavailable. Please retry.');
  const length=Number(response.headers.get('content-length'));
  if(length>40*1024*1024)return fail('This file needs a smaller preview export.',413);
  if((response.headers.get('content-type')||'').includes('text/html'))return fail('The source returned a page instead of the preview file.');
  let bytes=0;
  const body=response.body?.pipeThrough(new TransformStream({transform(chunk,controller){bytes+=chunk.byteLength;if(bytes>40*1024*1024)throw Error('Preview size limit exceeded');controller.enqueue(chunk)}}));
  return new Response(request.method==='HEAD'?null:body,{headers:{'content-type':'application/octet-stream','x-content-type-options':'nosniff','content-disposition':'attachment','cache-control':'public, max-age=86400'}});
 }catch{return fail('The preview source did not respond. Please retry.');}
}

